"""The committed public API reference matches the code (LAB-1586).

``docs/openapi.json`` and the error table in ``docs/api.md`` are generated by
``scripts/export_openapi.py``. When a public route, model or error code changes, these tests fail
until the script is run again and its output committed.
"""

from __future__ import annotations

import json
import runpy
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[1]
MODULE = runpy.run_path(str(ROOT / "scripts" / "export_openapi.py"))
HINT = "out of date: run `uv run python scripts/export_openapi.py` and commit the result"


@pytest.fixture(scope="module")
def spec() -> dict[str, Any]:
    return MODULE["build_spec"]()


def test_committed_spec_matches_the_code(spec: dict[str, Any]) -> None:
    committed = (ROOT / "docs" / "openapi.json").read_text(encoding="utf-8")
    assert committed == MODULE["render_spec"](spec), f"docs/openapi.json is {HINT}"


def test_committed_error_table_matches_the_code(spec: dict[str, Any]) -> None:
    guide = (ROOT / "docs" / "api.md").read_text(encoding="utf-8")
    assert guide == MODULE["render_guide"](guide, spec), f"docs/api.md's error table is {HINT}"


def test_export_is_deterministic(spec: dict[str, Any]) -> None:
    assert MODULE["render_spec"](MODULE["build_spec"]()) == MODULE["render_spec"](spec)


def test_a_changed_route_is_drift(spec: dict[str, Any]) -> None:
    """The comparison really looks at the routes: a changed summary no longer matches."""
    changed = json.loads(MODULE["render_spec"](spec))
    changed["paths"]["/v1/mask"]["post"]["summary"] = "Something else"
    committed = (ROOT / "docs" / "openapi.json").read_text(encoding="utf-8")
    assert MODULE["render_spec"](changed) != committed


def test_only_the_public_surface_is_exported(spec: dict[str, Any]) -> None:
    operations = {(m, p) for p, ops in spec["paths"].items() for m in ops}
    assert operations == {(m, p) for m, p, _ in MODULE["PUBLIC"]}
    for internal in ("/v1/status", "/v1/traffic", "/v1/vault", "/v1/account", "/v1/demo"):
        assert not any(p.startswith(internal) for p in spec["paths"]), internal
    # Projects and policies stay out; only an endpoint's keys are public.
    assert all("/keys" in p for p in spec["paths"] if p.startswith("/v1/projects"))


def test_every_reference_resolves(spec: dict[str, Any]) -> None:
    text = json.dumps(spec)
    for name in spec["components"]["schemas"]:
        assert f'"#/components/schemas/{name}"' in text, f"unused schema {name}"
    for ref in MODULE["_refs"](spec):
        assert ref in spec["components"]["schemas"], ref


def test_gateway_error_codes_are_documented(spec: dict[str, Any]) -> None:
    """The recent gateway codes, with the status of the exception that carries each."""
    rows = {(code, status) for status, code, _, _ in MODULE["error_rows"](spec)}
    assert {
        ("session_entry_limit_reached", 409),
        ("upstream_did_not_stream", 502),
        ("vault_capacity_exhausted", 503),
        ("unsupported_content", 400),
    } <= rows


def test_examples_are_fictional(spec: dict[str, Any]) -> None:
    """Only the reserved example.com domain, and no real-looking key (ADR 0005)."""
    text = MODULE["render_spec"](spec)
    assert "@" not in text.replace("teszt.elek@example.com", "")
    assert "pg_ep_EXAMPLE_ONLY" in text
