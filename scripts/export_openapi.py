def _version() -> str:
    with (ROOT / "pyproject.toml").open("rb") as fh:
        return str(tomllib.load(fh)["project"]["version"])


def _load(target: str) -> Any:
    module, _, name = target.partition(":")
    __import__(module)
    return getattr(sys.modules[module], name)


def _app_spec() -> dict[str, Any]:
    """The app's own OpenAPI document, built without the caller's environment."""
    from pii_guard.api.app import create_app
    from pii_guard.config import Settings

    saved = {k: os.environ.pop(k) for k in [k for k in os.environ if k.startswith("PII_GUARD_")]}
    try:
        settings = Settings(_env_file=None)  # type: ignore[call-arg]
        return create_app(settings).openapi()
    finally:
        os.environ.update(saved)


def gateway_errors() -> dict[str, tuple[int, str]]:
    """``code -> (status, when)`` for :data:`GATEWAY_ERRORS`, statuses from the exceptions."""
    from pii_guard.api.errors import ERROR_CODES

    return {
        code: (int(_load(target).status_code), when or ERROR_CODES[code][1])
        for code, (target, when) in GATEWAY_ERRORS.items()
    }


def _error_response(codes: list[tuple[str, int, str]]) -> dict[int, dict[str, Any]]:
    by_status: dict[int, list[tuple[str, str]]] = {}
    for code, status, when in codes:
        by_status.setdefault(status, []).append((code, when))
    out: dict[int, dict[str, Any]] = {}
    for status in sorted(by_status):
        listed = by_status[status]
        out[status] = {
            "description": " ".join(f"`{c}`: {w}" for c, w in listed),
            "content": {
                "application/json": {
                    "schema": {"$ref": "#/components/schemas/ErrorResponse"},
                    "examples": {
                        c: {"summary": w, "value": {"error": {"code": c, "message": c}}}
                        for c, w in listed
                    },
                }
            },
        }
    return out


def _merge_errors(op: dict[str, Any], codes: list[tuple[str, int, str]]) -> None:
    """Add error examples to ``op``'s responses, keeping the ones it already declares."""
    for status, extra in _error_response(codes).items():
        key = str(status)
        existing = op["responses"].get(key)
        if existing is None:
            op["responses"][key] = extra
            continue
        examples = existing["content"]["application/json"].setdefault("examples", {})
        for code, example in extra["content"]["application/json"]["examples"].items():
            if code not in examples:
                examples[code] = example
                existing["description"] += f" `{code}`: {example['summary']}"


def _json_body(schema: dict[str, Any], example: Any) -> dict[str, Any]:
    return {
        "required": True,
        "content": {"application/json": {"schema": schema, "example": example}},
    }


def _ok(description: str, example: Any, *, sse: bool = False) -> dict[str, Any]:
    content: dict[str, Any] = {
        "application/json": {"schema": {"type": "object"}, "example": example}
    }
    if sse:
        content["text/event-stream"] = {
            "schema": {"type": "string"},
            "example": 'data: {"choices":[{"delta":{"content":"Dear Teszt Elek"}}]}\n\n'
            "data: [DONE]\n\n",
        }
    return {
        "description": description,
        "headers": copy.deepcopy(GATEWAY_HEADERS),
        "content": content,
    }


def _shape_gateway(path: str, op: dict[str, Any]) -> None:
    errors = gateway_errors()
    if path == "/v1/models":
        op["summary"] = "List the upstream's models"
        op["description"] = (
            "The upstream's model list, passed through. On a pinned project endpoint: only "
            "the endpoint's model; on a pass-through endpoint, the provider's list."
        )
        op["responses"]["200"] = {
            "description": "OpenAI-style model list.",
            "content": {
                "application/json": {"schema": {"type": "object"}, "example": MODELS_EXAMPLE}
            },
        }
        from pii_guard.api.errors import COMMON_ERRORS, ERROR_CODES

        codes = [(c, *ERROR_CODES[c]) for c in COMMON_ERRORS]
        codes += [(c, *errors[c]) for c in MODELS_ERRORS]
    else:
        chat = path == "/v1/chat/completions"
        op["summary"] = "Create a chat completion" if chat else "Create a response"
        op["description"] = (
            "Mask the request, send it to the upstream, restore the placeholders in the answer. "
            "Text the guard finds is replaced with keyed placeholders (`[[PERSON_7f3a]]`); the "
            "upstream only ever sees those. Fail closed: on any error nothing is forwarded and "
            "no partially masked text is returned. A 200 stream can still end with an `error` "
            "event; a complete one ends with `data: [DONE]`."
        )
        op["parameters"] = [copy.deepcopy(SESSION_HEADER)]
        op["requestBody"] = _json_body(
            CHAT_REQUEST if chat else RESPONSES_REQUEST, CHAT_EXAMPLE if chat else RESPONSES_EXAMPLE
        )
        op["responses"]["200"] = _ok(
            "The upstream's answer with placeholders restored. With `stream: true`, "
            "server-sent events.",
            CHAT_RESPONSE_EXAMPLE if chat else RESPONSES_RESPONSE_EXAMPLE,
            sse=True,
        )
        codes = [
            (c, s, w) for c, (s, w) in errors.items() if chat or c != "upstream_did_not_stream"
        ]
        if chat:
            codes = [(c, s, w) for c, s, w in codes if c != "responses_unsupported"]
    _merge_errors(op, codes)
    op["security"] = [{"apiToken": []}, {"endpointKey": []}, {}]
    op["servers"] = [
        {"url": LOCAL, "description": "Self-hosted root gateway"},
        {
            "url": HOSTED + "/e/{endpoint_id}",
            "description": "Hosted project endpoint (copy the URL from Connect)",
            "variables": {"endpoint_id": {"default": "your-endpoint-id"}},
        },
    ]


