def _refs(node: Any) -> Iterator[str]:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
            yield ref.rsplit("/", 1)[1]
        for value in node.values():
            yield from _refs(value)
    elif isinstance(node, list):
        for value in node:
            yield from _refs(value)


def build_spec() -> dict[str, Any]:
    """The public OpenAPI document."""
    full = _app_spec()
    schemas = dict(full.get("components", {}).get("schemas", {}))
    schemas["EndpointKey"] = KEY_METADATA
    paths: dict[str, dict[str, Any]] = {}
    for method, path, tag in PUBLIC:
        op = copy.deepcopy(full["paths"][path][method])
        op["tags"] = [tag]
        if tag == "Gateway":
            _shape_gateway(path, op)
        elif tag == "Endpoint keys":
            _shape_keys(method, op)
        else:
            op["security"] = [{"apiToken": []}, {}]
        paths.setdefault(path, {})[method] = op
    # Only the schemas the public operations reach, transitively.
    used: set[str] = set()
    pending = list(_refs(paths))
    while pending:
        name = pending.pop()
        if name in used:
            continue
        used.add(name)
        pending.extend(_refs(schemas[name]))
    info = full["info"]
    return {
        "openapi": full["openapi"],
        "info": {
            "title": info["title"],
            "version": _version(),
            "description": (
                "Privacy firewall for AI agents: reversible PII masking. This is the public, "
                "read-only reference for the OpenAI-compatible gateway and the native masking "
                "routes. Guide, authentication and examples: "
                "https://github.com/watt-mind/pii-guard/blob/develop/docs/api.md. Every "
                "example is fictional."
            ),
            "license": {"name": "Apache-2.0", "identifier": "Apache-2.0"},
        },
        "servers": [
            {"url": LOCAL, "description": "Self-hosted (`pii-guard serve`)"},
            {"url": HOSTED, "description": "Hosted preview"},
        ],
        "tags": TAGS,
        "paths": paths,
        "components": {
            "schemas": {name: schemas[name] for name in sorted(used)},
            "securitySchemes": SECURITY_SCHEMES,
        },
    }


def render_spec(spec: dict[str, Any]) -> str:
    return json.dumps(spec, indent=2, ensure_ascii=False) + "\n"


def error_rows(spec: dict[str, Any]) -> list[tuple[int, str, str, list[str]]]:
    """``(status, code, when, routes)`` for every error the public spec declares."""
    rows: dict[tuple[int, str], tuple[str, list[str]]] = {}
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            for status, response in op["responses"].items():
                examples = (
                    response.get("content", {}).get("application/json", {}).get("examples", {})
                )
                for code, example in examples.items():
                    _, routes = rows.setdefault((int(status), code), (example["summary"], []))
                    routes.append(f"{method.upper()} {path}")
    return [(s, c, w, r) for (s, c), (w, r) in sorted(rows.items())]


def _route_label(routes: list[str], total: int) -> str:
    if len(routes) == total:
        return "every route"
    # "POST /v1/sessions/{session_id}/known-values" -> "sessions"; the key routes by name.
    short = {r.split(" ", 1)[1].removeprefix("/v1/").split("/{")[0] for r in routes}
    labels = sorted(f"`{s}`" for s in short if s != "projects")
    return ", ".join(labels + (["endpoint keys"] if "projects" in short else []))


def render_table(spec: dict[str, Any]) -> str:
    total = sum(len(ops) for ops in spec["paths"].values())
    lines = ["| Status | `code` | When | Routes |", "|---|---|---|---|"]
    for status, code, when, routes in error_rows(spec):
        cell = when.replace("|", "\\|")
        lines.append(f"| {status} | `{code}` | {cell} | {_route_label(routes, total)} |")
    return "\n".join([TABLE_BEGIN, *lines, TABLE_END])


def render_guide(guide: str, spec: dict[str, Any]) -> str:
    pattern = re.compile(re.escape(TABLE_BEGIN) + r".*?" + re.escape(TABLE_END), re.S)
    if not pattern.search(guide):
        raise SystemExit(f"{GUIDE_PATH.name}: the generated error table markers are missing")
    return pattern.sub(lambda _: render_table(spec), guide, count=1)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if the files are stale")
    args = parser.parse_args(argv)
    spec = build_spec()
    outputs = {
        SPEC_PATH: render_spec(spec),
        GUIDE_PATH: render_guide(GUIDE_PATH.read_text(encoding="utf-8"), spec),
    }
    stale = [
        p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
    if args.check:
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date: run scripts/export_openapi.py")
        return 1 if stale else 0
    for path in stale:
        path.write_text(outputs[path], encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
