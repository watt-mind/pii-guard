"""Export the public API reference: ``docs/openapi.json`` and the error table in ``docs/api.md``.

The spec is generated from the FastAPI app (:func:`pii_guard.api.app.create_app`) and filtered
to the public surface (LAB-1586): the OpenAI-compatible gateway (``/v1/chat/completions``,
``/v1/responses``, ``/v1/models``), ``/v1/mask``, ``/v1/unmask``, ``/v1/analyze``, vault
sessions and endpoint keys. Internal, admin and hosted-only routes (status, traffic, vault
inspector, projects and policies, account, demo) are left out.

The gateway routes read their body as raw JSON (the request walker validates it), so the app
declares no schema for them; this script adds a minimal OpenAI-compatible shape, the gateway
headers and the gateway's own error codes (with the status of the exception that carries
each). Every example is fictional (ADR 0005): Teszt Elek, ``example.com``.

The output is deterministic: no timestamps, no environment (``PII_GUARD_*`` variables and
``.env`` are ignored) and the version comes from ``pyproject.toml``. Run it after changing a
public route; ``tests/test_openapi_export.py`` fails while the committed files differ.

    uv run python scripts/export_openapi.py          # write both files
    uv run python scripts/export_openapi.py --check  # exit 1 if either is stale
"""

