import { describe, expect, it } from "vitest";
import {
  documentCount,
  formatMs,
  formatPct,
  languageName,
  loadBenchmarks,
  originLabel,
  pick,
  snapshotsFor,
  systemsOn,
  textSets,
} from "./benchmarks";

describe("benchmark index helpers", () => {
  it("loads the bundled index (generated by pii-guard eval report)", async () => {
    const index = await loadBenchmarks();
    expect(index.schema_version).toBe(1);
    expect(index.runs.length).toBeGreaterThan(0);
    expect(index.headline_set && index.fixture_sets[index.headline_set]).toBeTruthy();
  });

  it("lists text sets with the headline first and systems in index order", async () => {
    const index = await loadBenchmarks();
    const sets = textSets(index);
    expect(sets[0]).toBe(index.headline_set);
    expect(sets).not.toContain("specimens");
    const systems = systemsOn(index, sets[0]!);
    expect(systems).toEqual(Object.keys(index.systems).filter((k) => systems.includes(k)));
    expect(snapshotsFor(index, sets[0]!, ["presidio", "nope"]).map((s) => s.system)).toEqual(["presidio"]);
  });

  it("picks pooled or per-language metrics", async () => {
    const index = await loadBenchmarks();
    const s = index.snapshots[0]!;
    expect(pick(s, "all")).toBe(s.all);
    expect(pick(s, "xx")).toBeNull();
    const lang = Object.keys(s.languages)[0]!;
    expect(pick(s, lang)).toBe(s.languages[lang]);
  });

  it("formats rates, latency, languages and set origins", () => {
    expect(formatPct(0.5123)).toBe("51.2%");
    expect(formatPct(null)).toBe("–");
    expect(formatMs(0.123)).toBe("0.12 ms");
    expect(formatMs(4.56)).toBe("4.6 ms");
    expect(formatMs(61.2)).toBe("61 ms");
    expect(formatMs(9876)).toBe("9.9 s");
    expect(languageName("hu")).toBe("Hungarian");
    const info = { origin: "generated", kind: "text" as const, languages: ["en", "hu"], documents: { en: 10, hu: 20 }, generators: ["muse"] };
    expect(originLabel(info)).toBe("generated by muse");
    expect(documentCount(info, "all")).toBe(30);
    expect(documentCount(info, "hu")).toBe(20);
  });
});
