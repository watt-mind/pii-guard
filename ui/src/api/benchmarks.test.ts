import type { BenchmarkIndex } from "./benchmarks";
import { describe, expect, it } from "vitest";
import {
  coverageTag,
  documentCount,
  headline,
  missingLanguages,
  tidyLabels,
  formatMs,
  formatPct,
  languageName,
  loadBenchmarks,
  originLabel,
  pick,
  snapshotsFor,
  systemsOn,
  textSets,
} from "./benchmarks";

describe("benchmark index helpers", () => {
  it("loads the bundled index (generated by pii-guard eval report)", async () => {
    const index = await loadBenchmarks();
    expect(index.schema_version).toBe(1);
    expect(index.runs.length).toBeGreaterThan(0);
    expect(index.headline_set && index.fixture_sets[index.headline_set]).toBeTruthy();
  });

  it("lists text sets with the headline first and systems in index order", async () => {
    const index = await loadBenchmarks();
    const sets = textSets(index);
    expect(sets[0]).toBe(index.headline_set);
    expect(sets).not.toContain("specimens");
    const systems = systemsOn(index, sets[0]!);
    expect(systems).toEqual(Object.keys(index.systems).filter((k) => systems.includes(k)));
    expect(snapshotsFor(index, sets[0]!, ["presidio", "nope"]).map((s) => s.system)).toEqual(["presidio"]);
  });

  it("picks pooled or per-language metrics", async () => {
    const index = await loadBenchmarks();
    const s = index.snapshots[0]!;
    expect(pick(s, "all")).toBe(s.all);
    expect(pick(s, "xx")).toBeNull();
    const lang = Object.keys(s.languages)[0]!;
    expect(pick(s, lang)).toBe(s.languages[lang]);
  });

  it("formats rates, latency, languages and set origins", () => {
    expect(formatPct(0.5123)).toBe("51.2%");
    expect(formatPct(null)).toBe("–");
    expect(formatMs(0.123)).toBe("0.12 ms");
    expect(formatMs(4.56)).toBe("4.6 ms");
    expect(formatMs(61.2)).toBe("61 ms");
    expect(formatMs(9876)).toBe("9.9 s");
    expect(languageName("hu")).toBe("Hungarian");
    const info = { origin: "generated", kind: "text" as const, languages: ["en", "hu"], documents: { en: 10, hu: 20 }, generators: ["muse"] };
    expect(originLabel(info)).toBe("generated by muse");
    expect(documentCount(info, "all")).toBe(30);
    expect(documentCount(info, "hu")).toBe(20);
  });
});

describe("headline", () => {
  it("compares the lowest-leak pii-guard configuration with the lowest-leak tool", async () => {
    const { headline } = await import("./benchmarks");
    const index = (await import("virtual:pii-guard/benchmarks-index")).default as BenchmarkIndex;
    const set = index.headline_set ?? "smoke";
    const h = headline(index, set, "all");
    expect(h).not.toBeNull();
    expect(index.systems[h!.ours.system]!.family).toBe("pii-guard");
    expect(index.systems[h!.theirs.system]!.family).toBe("comparison");
    expect(h!.ours.leak).toBeLessThanOrEqual(h!.theirs.leak);
  });

  it("builds the pooled headline only from systems run on every language of the set", async () => {
    const index = await loadBenchmarks();
    const set = index.headline_set!;
    const h = headline(index, set, "all")!;
    for (const side of [h.ours, h.theirs]) {
      const snap = index.snapshots.find((x) => x.fixture_set === set && x.system === side.system)!;
      expect(missingLanguages(index, snap)).toEqual([]);
      expect(coverageTag(index, snap)).toBeNull();
    }
    const partial = index.snapshots.find((x) => x.fixture_set === set && missingLanguages(index, x).length > 0);
    if (partial) expect(coverageTag(index, partial)).toMatch(/^[A-Z]{2}( \+ [A-Z]{2})* only$/);
  });

  it("spells detector names one way in labels", async () => {
    const index = tidyLabels(await loadBenchmarks());
    expect(Object.values(index.systems).some((v) => /\bner\b/.test(v.label) || /\bner\b/.test(v.short_label ?? ""))).toBe(false);
  });
});
