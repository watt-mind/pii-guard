"""Journey milestones as one file each, folded into ``docs/journey.md`` with render-time numbers.

Two pull requests that each appended "milestone 34" to ``docs/journey.md`` always conflicted:
both edit the same lines at the end of the list, and both picked the same number. Now a
milestone is its own file, ``docs/journey/<YYYY-MM-DD>-<ticket>-<slug>.md``, so two pull requests
add two different files. The file reads on its own on GitHub::

    # The benchmark report compares like with like (2026-10-27)

    LAB-1234. What changed, before → after, cost.

    ## Details          <- any sub-heading; rendered two levels down

:func:`render` folds every entry into the generated block of ``docs/journey.md`` (between
:data:`BEGIN` and :data:`END`), after the hand-written milestones, as ``### <n>. <title>``.
Numbers are assigned here, not by the author, and never change once given:

- an entry already in the block keeps its number (the block is the registry, as
  ``docs/benchmarks/colours.json`` is for chart colours);
- a new entry takes the next number after every number in the document, hand-written ones
  included, in file-name order. Rendered after each merge, that is merge order.

Relative links are rewritten for the new location (``../../eval/...`` → ``../eval/...``), and
sub-headings move down two levels so they sit under the milestone heading.

Hand-written milestones outside the block are never touched. A heading inside the block that
no entry file produced, or a number used twice in the document, is an error: it means someone
edited generated text, or numbered a milestone by hand that the block already uses.
"""

from __future__ import annotations

import posixpath
import re
from collections.abc import Mapping
from dataclasses import dataclass
from pathlib import Path

__all__ = [
    "BEGIN",
    "DEFAULT_ENTRIES_DIR",
    "DEFAULT_JOURNEY",
    "END",
    "Entry",
    "JourneyError",
    "load_entries",
    "numbers_of",
    "render",
]

DEFAULT_JOURNEY = Path("docs/journey.md")
DEFAULT_ENTRIES_DIR = Path("docs/journey")

BEGIN = (
    "<!-- journey:begin. Generated by `pii-guard eval report --journey` from docs/journey/*.md;"
    " edit those files, not this block. -->"
)
END = "<!-- journey:end -->"
_SOURCE = "<!-- journey:source {} -->"

_NAME = re.compile(r"^\d{4}-\d{2}-\d{2}-[a-z0-9][a-z0-9-]*\.md$")
_SOURCE_RE = re.compile(r"^<!-- journey:source (\S+) -->$")
_MILESTONE = re.compile(r"^### (\d+)\. ", re.M)
_HEADING = re.compile(r"^(#{1,6})(\s+.*)$")
_FENCE = re.compile(r"^\s*(```|~~~)")
# [text](target "title"), [ref]: target, src="target", href="target"
_INLINE_LINK = re.compile(r"(\]\()(<?)([^)\s>]+)(>?(?:\s+\"[^\"]*\")?\))")
_REF_LINK = re.compile(r"^(\s{0,3}\[[^\]]+\]:\s+)(<?)(\S+?)(>?)(\s.*)?$")
_HTML_ATTR = re.compile(r"((?:src|href)=\")([^\"]+)(\")")


class JourneyError(ValueError):
    """An entry file or ``docs/journey.md`` that can't be rendered."""


@dataclass(frozen=True)
class Entry:
    """One milestone file: where it lives, its title line and its body, as written."""

    path: str  # repository-relative, posix: docs/journey/2026-10-27-lab-1269-....md
    title: str
    body: str


def load_entries(entries_dir: Path = DEFAULT_ENTRIES_DIR) -> list[Entry]:
    """Every entry file in ``entries_dir``, in file-name order. ``README.md`` is not one."""
    if not entries_dir.is_dir():
        return []
    out = []
    for path in sorted(entries_dir.glob("*.md")):
        if path.name == "README.md":
            continue
        rel = path.as_posix()
        if not _NAME.match(path.name):
            raise JourneyError(
                f"{rel}: name it <YYYY-MM-DD>-<ticket>-<slug>.md, lower case "
                "(e.g. 2026-10-27-lab-1269-no-merge-conflicts.md)"
            )
        text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
        lines = text.split("\n")
        first = next((i for i, line in enumerate(lines) if line.strip()), None)
        if first is None or not lines[first].startswith("# "):
            raise JourneyError(f"{rel}: the first line must be the title, '# <title> (<date>)'")
        title = lines[first][2:].strip()
        if not title:
            raise JourneyError(f"{rel}: empty title")
        body = "\n".join(lines[first + 1 :]).strip("\n")
        out.append(Entry(path=rel, title=title, body=body))
    return out


def _relink(target: str, src_dir: str, dst_dir: str, dst_name: str) -> str:
    """``target`` as written in ``src_dir``, rewritten to work from ``dst_dir``."""
    if not target or target.startswith(("#", "/")) or re.match(r"^[a-z][a-z0-9+.-]*:", target):
        return target
    path, sep, anchor = target.partition("#")
    if not path:
        return target
    moved = posixpath.relpath(posixpath.normpath(posixpath.join(src_dir, path)), dst_dir)
    if path.endswith("/") and not moved.endswith("/"):
        moved += "/"
    if moved == dst_name and anchor:
        return f"#{anchor}"  # a link to another milestone of the same page
    return moved + sep + anchor


def _adapt(body: str, src_dir: str, dst_dir: str, dst_name: str) -> str:
    """The entry body for the journey page: links rewritten, sub-headings two levels down."""

    def fix(target: str) -> str:
        return _relink(target, src_dir, dst_dir, dst_name)

    out = []
    fenced = False
    for line in body.split("\n"):
        if _FENCE.match(line):
            fenced = not fenced
            out.append(line)
            continue
        if fenced:
            out.append(line)
            continue
        heading = _HEADING.match(line)
        if heading:
            level = min(len(heading.group(1)) + 2, 6)
            line = "#" * level + heading.group(2)
        ref = _REF_LINK.match(line)
        if ref:
            line = (
                ref.group(1)
                + ref.group(2)
                + fix(ref.group(3))
                + ref.group(4)
                + (ref.group(5) or "")
            )
        else:
            line = _INLINE_LINK.sub(
                lambda m: m.group(1) + m.group(2) + fix(m.group(3)) + m.group(4), line
            )
        line = _HTML_ATTR.sub(lambda m: m.group(1) + fix(m.group(2)) + m.group(3), line)
        out.append(line)
    return "\n".join(out)


def _split(doc: str, where: str) -> tuple[str, str, str]:
    """``(before, block, after)``; the block is the text strictly between the markers."""
    if doc.count(BEGIN) != 1 or doc.count(END) != 1:
        raise JourneyError(
            f"{where}: needs exactly one '<!-- journey:begin. ... -->' line and one '{END}' "
            "line (copy them from docs/journey/README.md)"
        )
    before, rest = doc.split(BEGIN, 1)
    block, after = rest.split(END, 1)
    return before, block, after


def _registry(block: str, where: str) -> dict[str, int]:
    """``{entry path: number}`` of the entries already rendered in the block."""
    numbers: dict[str, int] = {}
    pending: str | None = None
    for line in block.split("\n"):
        source = _SOURCE_RE.match(line.strip())
        if source:
            pending = source.group(1)
            continue
        milestone = _MILESTONE.match(line)
        if milestone:
            if pending is None:
                raise JourneyError(
                    f"{where}: '{line.strip()}' is inside the generated block but no entry file "
                    "produced it; move it to docs/journey/ or above the block"
                )
            numbers[pending] = int(milestone.group(1))
        if line.strip():
            pending = None
    return numbers


def render(
    doc: str,
    entries: list[Entry],
    *,
    journey_path: Path = DEFAULT_JOURNEY,
) -> str:
    """``doc`` (the current ``docs/journey.md``) with its block rebuilt from ``entries``."""
    where = journey_path.as_posix()
    before, block, after = _split(doc, where)
    kept = _registry(block, where)
    hand = [int(n) for n in _MILESTONE.findall(before + after)]
    seen: dict[int, str] = {}
    for n in hand:
        if n in seen:
            raise JourneyError(f"{where}: milestone {n} is numbered twice by hand")
        seen[n] = "a hand-written heading"
    present = {e.path for e in entries}
    numbers: dict[str, int] = {p: n for p, n in kept.items() if p in present}
    for path, n in numbers.items():
        if n in seen:
            raise JourneyError(
                f"{where}: milestone {n} is both {seen[n]} and {path}; renumber the "
                "hand-written one (or move it to docs/journey/)"
            )
        seen[n] = path
    following = max(seen, default=0)
    for entry in entries:
        if entry.path not in numbers:
            following += 1
            numbers[entry.path] = following
    dst_dir = posixpath.dirname(where)
    dst_name = posixpath.basename(where)
    parts = []
    for entry in sorted(entries, key=lambda e: numbers[e.path]):
        src_dir = posixpath.dirname(entry.path)
        body = _adapt(entry.body, src_dir, dst_dir, dst_name)
        parts.append(
            f"{_SOURCE.format(entry.path)}\n### {numbers[entry.path]}. {entry.title}\n\n{body}\n"
        )
    inner = "\n" + "\n".join(parts) + "\n" if parts else "\n"
    return before + BEGIN + inner + END + after


def numbers_of(doc: str) -> Mapping[str, int]:
    """The rendered entries of ``doc`` and their numbers (for tests and tooling)."""
    _, block, _ = _split(doc, "journey")
    return _registry(block, "journey")
