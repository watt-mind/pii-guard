"""Bootstrap 95 % confidence intervals per dataset and system, and their benchmarks.md section.

Reads the per-document counts that :mod:`pii_guard.eval.datasets.run` writes next to each run
record (``eval/datasets/results/<run_id>.json``) and resamples **documents** with replacement
(:data:`RESAMPLES` times, fixed seed), recomputing each pooled rate from the resampled counts:
a percentile interval (2.5th to 97.5th). Documents, not spans, are resampled because spans in
one document are not independent (one missed name usually leaks every repetition of it).

The section is generated by ``pii-guard eval report`` into ``docs/benchmarks.md``.
"""

from __future__ import annotations

import json
import random
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

__all__ = ["RESAMPLES", "SEED", "bootstrap", "load_counts", "render_section", "summarize"]

RESAMPLES = 1000
SEED = 1226

Docs = Sequence[Mapping[str, Any]]


def _ratio(num: float, den: float) -> float | None:
    return num / den if den else None


_FIELDS = ("gold", "tp_gold", "pred", "tp_pred", "values", "leaked", "masked", "over_masked")


def _rates(t: Sequence[float]) -> dict[str, float | None]:
    gold, tp_gold, pred, tp_pred, values, leaked, masked, over = t
    p, r = _ratio(tp_pred, pred), _ratio(tp_gold, gold)
    f1 = None if p is None or r is None else (0.0 if p + r == 0 else 2 * p * r / (p + r))
    return {
        "leak": _ratio(leaked, values),
        "precision": p,
        "recall": r,
        "f1": f1,
        "over_masking": _ratio(over, masked),
    }


METRICS = ("leak", "precision", "recall", "f1", "over_masking")


def _percentile(values: Sequence[float], q: float) -> float:
    ordered = sorted(values)
    k = (len(ordered) - 1) * q
    lo, hi = int(k), min(int(k) + 1, len(ordered) - 1)
    return ordered[lo] + (ordered[hi] - ordered[lo]) * (k - lo)


def bootstrap(
    docs: Docs, *, resamples: int = RESAMPLES, seed: int = SEED
) -> dict[str, dict[str, float | None]]:
    """``{metric: {value, low, high}}`` over ``docs``; ``None`` where a rate is undefined.

    Each resample draws ``len(docs)`` documents with replacement and recomputes every pooled
    rate from their summed counts.
    """
    columns = [[float(d[f]) for d in docs] for f in _FIELDS]
    point = _rates([sum(c) for c in columns])
    draws: dict[str, list[float]] = {m: [] for m in METRICS}
    n = len(docs)
    if n:
        rng = random.Random(seed)  # noqa: S311 (a seeded resample, not a secret)
        population = range(n)
        for _ in range(resamples):
            idx = rng.choices(population, k=n)
            rates = _rates([sum(col[i] for i in idx) for col in columns])
            for m in METRICS:
                v = rates[m]
                if v is not None:
                    draws[m].append(v)
    out: dict[str, dict[str, float | None]] = {}
    for m in METRICS:
        values = draws[m]
        ok = point[m] is not None and values
        out[m] = {
            "value": _round(point[m]),
            "low": _round(_percentile(values, 0.025)) if ok else None,
            "high": _round(_percentile(values, 0.975)) if ok else None,
        }
    return out


def _round(v: float | None) -> float | None:
    return None if v is None else round(v, 6)


def _latency(docs: Docs, q: float) -> float | None:
    values = [d["detect_ms"] for d in docs if d.get("detect_ms") is not None]
    return round(_percentile(values, q), 3) if values else None


def summarize(docs: Docs, *, resamples: int = RESAMPLES) -> dict[str, Any]:
    """Point estimates, intervals, latency and the by-construction leak splits of one run.

    Stored in the counts file when the run is recorded, so ``pii-guard eval report`` only reads
    it; ``tests/eval/test_datasets_ci.py`` recomputes it from the documents.
    """
    out: dict[str, Any] = {"documents": len(docs), "resamples": resamples, "seed": SEED}
    out.update(bootstrap(docs, resamples=resamples))
    out["p50_ms"] = _latency(docs, 0.5)
    out["p95_ms"] = _latency(docs, 0.95)
    for key, buckets in (("checksum", ("true", "false")), ("perturbed", ("perturbed",))):
        if not any(key in d for d in docs):
            continue
        split = {}
        for b in buckets:
            values = sum(d.get(key, {}).get(f"{b}_values", 0) for d in docs)
            leaked = sum(d.get(key, {}).get(f"{b}_leaked", 0) for d in docs)
            split[b] = {"values": values, "leaked": leaked, "rate": _round(_ratio(leaked, values))}
        out[key] = split
    return out


def load_counts(directory: Path) -> list[dict[str, Any]]:
    """Every counts file, oldest run first (run ids sort by date)."""
    if not directory.is_dir():
        return []
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(directory.glob("*.json"))]


def _pct(v: float | None) -> str:
    return "-" if v is None else f"{v * 100:.1f}"


def _cell(m: Mapping[str, Any]) -> str:
    if m["value"] is None:
        return "-"
    if m["low"] is None:
        return _pct(m["value"])
    return f"{_pct(m['value'])} ({_pct(m['low'])}-{_pct(m['high'])})"


def _ms(v: float | None) -> str:
    if v is None:
        return "-"
    return f"{v:,.0f}" if v >= 100 else f"{v:.1f}"


#: Systems in the order the tables list them.
_ORDER = ("rules", "rules+ner", "rules+ner+llm", "presidio", "llm-guard", "privaite")


def _order(key: str) -> tuple[int, str]:
    base = "+".join(part.split(":")[0].split("@")[0] for part in key.split("+"))
    return (_ORDER.index(base) if base in _ORDER else len(_ORDER), key)


def render_section(
    counts: Sequence[Mapping[str, Any]],
    datasets: Sequence[tuple[str, str, str]],
    *,
    resamples: int = RESAMPLES,
) -> str:
    """The "Results per dataset" section. ``datasets`` is ``(name, title, split)`` in order."""
    latest: dict[tuple[str, str], Mapping[str, Any]] = {}
    for c in counts:  # oldest first, so the newest run of a system on a set wins
        latest[(c["dataset"], c["system"]["key"])] = c
    if not latest:
        return ""
    out = [
        "## Results per dataset\n",
        "Every registered dataset ([datasets.md](datasets.md): licences, splits, label "
        "mapping) with the latest run of each system. Rates in %, pooled over the set's "
        f"languages; in brackets the 95 % bootstrap interval ({resamples:,} resamples of "
        "documents, seed 1226, from the per-document counts in "
        "[`eval/datasets/results/`](../eval/datasets/results/)). Precision, recall and F1 by "
        "overlap. Latency: detection per document on the machine in each run's record. "
        "Only `test` splits are headline numbers.\n",
    ]
    for name, title, split in datasets:
        rows = sorted(
            ((key, c) for (ds, key), c in latest.items() if ds == name), key=lambda t: _order(t[0])
        )
        if not rows:
            continue
        out.append(f"### `{name}`: {title} ({split} split)\n")
        out.append(
            "| System | Docs | Leak | Precision | Recall | F1 | Over-masking | p50 ms | p95 ms |"
        )
        out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
        extra: list[str] = []
        for _, c in rows:
            s = c.get("summary") or summarize(c["documents"], resamples=resamples)
            label = c["system"]["label"]
            out.append(
                f"| {label} | {s['documents']} | {_cell(s['leak'])} | {_cell(s['precision'])} | "
                f"{_cell(s['recall'])} | {_cell(s['f1'])} | {_cell(s['over_masking'])} | "
                f"{_ms(s['p50_ms'])} | {_ms(s['p95_ms'])} |"
            )
            if "checksum" in s or "perturbed" in s:
                ck = s.get("checksum", {})
                pt = s.get("perturbed", {})
                extra.append(
                    f"| {label} | {_pct(ck.get('true', {}).get('rate'))} "
                    f"({ck.get('true', {}).get('values', 0)}) | "
                    f"{_pct(ck.get('false', {}).get('rate'))} "
                    f"({ck.get('false', {}).get('values', 0)}) | "
                    f"{_pct(pt.get('perturbed', {}).get('rate'))} "
                    f"({pt.get('perturbed', {}).get('values', 0)}) |"
                )
        out.append("")
        if extra:
            out.append(
                "Leak by construction (values in brackets): identifiers whose checksum passes, "
                "those altered to fail it, and values with an adversarial perturbation.\n"
            )
            out.append("| System | Valid checksum | Invalid checksum | Perturbed |")
            out.append("|---|---:|---:|---:|")
            out.extend(extra)
            out.append("")
    return "\n".join(out) + "\n"
