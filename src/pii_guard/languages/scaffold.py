"""``pii-guard lang new <code>``: generate a language pack skeleton.

The skeleton passes the structural conformance checks as generated; the conformance suite then
fails only on the smoke fixtures, which are the first thing to write (``docs/languages.md``).
It writes:

- ``<dest>/<code>/__init__.py``: the :class:`~pii_guard.languages.LanguagePack`, with every
  optional part commented and pointing at the German pack for a worked example;
- ``<dest>/<code>/rules.py``: empty ``EVERYWHERE`` / ``RULES`` and a commented example rule;
- ``<dest>/<code>/prompt.md``: generic LLM notes to replace with the language's own;
- ``<fixtures>/<code>-smoke.jsonl.example``: one fictional document in the fixture format;
- optionally ``<tests>/test_<code>_pack.py``: a test hook running the conformance suite (for
  a pack in its own distribution; inside this repository ``tests/languages`` already runs it
  for every registered pack).
"""

from __future__ import annotations

import json
import keyword
from dataclasses import dataclass
from pathlib import Path

from pii_guard.languages import CODE_RE

__all__ = ["ScaffoldError", "ScaffoldResult", "new_pack"]


class ScaffoldError(ValueError):
    """Bad arguments, or the pack directory already exists."""


@dataclass(frozen=True, slots=True)
class ScaffoldResult:
    package: Path
    written: tuple[Path, ...]


_INIT = '''"""The {name} language pack (``{code}``). Generated by ``pii-guard lang new``.

Fill in the parts in the order of ``docs/languages.md``; ``pii-guard lang check {code}``
says what is still missing. ``pii_guard/languages/de/`` is a complete worked example.
"""

from __future__ import annotations

from importlib.resources import files

from pii_guard.languages import LanguagePack, SurfaceForms

__all__ = ["pack"]


def pack() -> LanguagePack:
    # Import the parts inside the function: packs load lazily, on first use.
    from . import rules

    return LanguagePack(
        code="{code}",
        name="{name}",
        prompt=files(__name__).joinpath("prompt.md"),
        # Relative names are looked up in eval/fixtures/; a separate distribution can pass an
        # absolute path (str(Path(__file__).parent / "fixtures" / "{code}-smoke.jsonl")).
        smoke_fixtures=("{code}-smoke.jsonl",),
        everywhere=rules.EVERYWHERE,
        rules=rules.RULES,
        # inflection=MyMatcher(),  # if values take suffixes (see languages/de/inflection.py)
        surface_forms=SurfaceForms(stopwords=frozenset()),  # street words, months, legal forms
        # country_entity_types=(),  # country-specific EntityTypes the LLM should be asked for
        # allow_suffix=True,  # may a name run on into a longer word? (False for English)
        # word_boundary=True,  # False for scripts written without spaces between words
        # lexicons=LexiconSpec(...),  # name and place lists (see languages/hu/__init__.py)
        # captions=files(__name__).joinpath("captions.tsv"),  # ID card field captions
    )
'''

_RULES = '''"""{name} rules. Generated by ``pii-guard lang new``.

``EVERYWHERE``: identifiers with a checksum or a distinctive validated format; they run for
every language. ``RULES``: formats that are only unambiguous in {name} text (postcodes,
national phone formats); they run only when the text is in ``{code}``. Every rule takes the
whole text and yields ``_Hit(start, end, entity_type, score)`` for validated matches only.
"""

from __future__ import annotations

from pii_guard.detect.rules._base import Rule

__all__ = ["EVERYWHERE", "RULES"]

# Example (see languages/de/rules.py for complete ones):
#
# import re
# from collections.abc import Iterator
# from pii_guard.detect.rules._base import NUM_END, NUM_START, _Hit, context_before
# from pii_guard.types import EntityType
#
# _ID_RE = re.compile(NUM_START + r"(\\d{{9}})" + NUM_END)
#
# def _find_national_id(text: str) -> Iterator[_Hit]:
#     for m in _ID_RE.finditer(text):
#         if is_valid_national_id(m.group(1)):  # a checksum keeps precision high
#             yield _Hit(m.start(1), m.end(1), EntityType.ID_DOCUMENT, 0.95)

EVERYWHERE: tuple[Rule, ...] = ()
RULES: tuple[Rule, ...] = ()
'''

_PROMPT = """- Report names, addresses and identifiers exactly as they are written in the
  {name} text, including every inflected form of a name.
- Do not include titles or forms of address unless they are part of a written name.
- Do not report generic roles (the seller, the tenant) as persons.
"""

_TEST = '''"""Conformance hook for the {name} pack (generated by ``pii-guard lang new``)."""

from pii_guard.languages.conformance import assert_conformant


def test_{ident}_pack_conforms() -> None:
    assert_conformant("{code}")
'''


def _example_line(code: str) -> str:
    text = "Example: write to Sample Person at sample.person@example.com."
    name, email = "Sample Person", "sample.person@example.com"
    spans = [
        {"start": text.index(name), "end": text.index(name) + len(name), "entity_type": "PERSON"},
        {"start": text.index(email), "end": text.index(email) + len(email), "entity_type": "EMAIL"},
    ]
    record = {
        "id": f"{code}-example-0001",
        "language": code,
        "text": text,
        "spans": spans,
        "meta": {"kind": "example"},
    }
    return json.dumps(record, ensure_ascii=False) + "\n"


def new_pack(
    code: str,
    name: str,
    *,
    dest: str | Path,
    fixtures_dir: str | Path | None = None,
    tests_dir: str | Path | None = None,
    force: bool = False,
) -> ScaffoldResult:
    """Write a pack skeleton for ``code`` under ``dest`` (see the module docstring)."""
    if not CODE_RE.match(code) or keyword.iskeyword(code):
        raise ScaffoldError(f"{code!r} is not a lowercase ISO 639-1/639-3 code like 'de'")
    if not name.strip() or any(ch in name for ch in '"\\\n'):
        raise ScaffoldError("--name must be the language's English name, e.g. 'German'")
    package = Path(dest) / code
    if package.exists() and not force:
        raise ScaffoldError(f"{package} already exists (use --force to overwrite)")
    files: dict[Path, str] = {
        package / "__init__.py": _INIT.format(code=code, name=name),
        package / "rules.py": _RULES.format(code=code, name=name),
        package / "prompt.md": _PROMPT.format(name=name),
    }
    if fixtures_dir is not None:
        files[Path(fixtures_dir) / f"{code}-smoke.jsonl.example"] = _example_line(code)
    if tests_dir is not None:
        files[Path(tests_dir) / f"test_{code}_pack.py"] = _TEST.format(
            code=code, name=name, ident=code
        )
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
    return ScaffoldResult(package=package, written=tuple(files))
